#!/usr/bin/env python3
"""Write tables.inc, the constant tables of rom_e12_slicer.asm56k and slicer_model.py.

  PITCH  2^(n/12) / 4 for n = 0..12 (one octave of semitones, plus its top)
  QTR    1 - k/4 for k = 0..4 (crossfade steps)
  DECAY  envelope multiplier per 32-sample block for DEC 0..127, as SMP-ST:
         DEC 1..126 fall 60 dB in about 0.03 .. 30 s; 127 holds the level, and
         so does 0 (play once, no envelope).
  SPEED  playhead speed for TIME 0..127 (8192 = normal), as SMP-ST: 42 is half
         speed, 127 frozen.
  EXPC   MODE EXP: slice boundary at t = k/n is (2^(c t) - 1) / (2^c - 1), so
         slices get longer along the sample (last / first about 2^c).
  LOGC   MODE LOG: log2(1 + (2^c - 1) t) / c, the inverse curve: slices get shorter.
         Both are 65 points over t = 0..1, interpolated linearly.
  FADE8  DEC 0 end fade over 8 blocks: 1 - smoothstep(k/8), k = 0..8.
  NOISE  512 entries of 1-D Perlin noise (+-NOISE_MAX). MODE 4..127 are 124 seeds
         reading it with their own offset, stride and depth (seed_params); with n
         slices, boundary k is at P[k] / P[n], P the prefix sums of the widths,
         so the first n widths are always stretched over the whole sample.
"""
import math
import random
from pathlib import Path

DEC_MIN_S, DEC_MAX_S = 0.03, 30.0
TIME_HALF_AT = 42
TIME_CURVE = math.log(0.5) / math.log(1 - TIME_HALF_AT / 127)
CURVE_C = 3.0                          # EXP / LOG steepness: about 8:1 between the first and last slice

Q23 = 1 << 23
PITCH = [round(2 ** (n / 12) / 4 * Q23) for n in range(13)]
QTR = [0x7FFFFF, 0x600000, 0x400000, 0x200000, 0]
DECAY = [min(0x7FFFFF, round(10 ** (-3 * 32 / (44100 * DEC_MIN_S * (DEC_MAX_S / DEC_MIN_S) ** (d / 126)))
                             * Q23)) for d in range(127)] + [0x7FFFFF]
DECAY[0] = 0x7FFFFF
SPEED = [round(8192 * (1 - t / 127) ** TIME_CURVE) for t in range(128)]


def q23(v):
    return min(0x7FFFFF, max(0, round(v * Q23)))


EXPC = [q23((2 ** (CURVE_C * i / 64) - 1) / (2 ** CURVE_C - 1)) for i in range(65)]
LOGC = [q23(math.log2(1 + (2 ** CURVE_C - 1) * i / 64) / CURVE_C) for i in range(65)]


def perlin_table(n=512, cell=8, seed=5):
    """1-D gradient (Perlin) noise, one lattice point every `cell` entries,
    scaled so the largest magnitude is NOISE_MAX."""
    rnd = random.Random(seed)
    grad = [rnd.uniform(-1, 1) for _ in range(n // cell + 2)]
    raw = []
    for i in range(n):
        x = i / cell
        k = math.floor(x)
        f = x - k
        fade = f * f * f * (f * (f * 6 - 15) + 10)
        a, b = grad[k] * f, grad[k + 1] * (f - 1)
        raw.append(a + fade * (b - a))
    # Equalise: replace each value by its rank, spread evenly over +-NOISE_MAX.
    # Perlin values crowd round zero; this keeps the shape (the order of the
    # values) but lets the depth reach the full range of widths.
    order = sorted(range(n), key=lambda i: raw[i])
    out = [0] * n
    for r, i in enumerate(order):
        out[i] = round((2 * r / (n - 1) - 1) * NOISE_MAX)
    return out


# Perlin seeds (MODE 4..127, seed j = MODE - 4, 0..123). Slice k's width is
# NOISE_MAX + depth * N[offset + k * stride]; the noise is read further apart
# (busier) and with more depth (more uneven) as j rises:
#   depth  = DEPTH0 + DSPAN * j / 128      (0.15 .. 0.94)
#   stride = 1 + j / 32                     (1 .. 4)
#   offset = floor(frac(j * GOLD) * OFFMAX) (golden-ratio scatter over the table)
NOISE_MAX = 4096
NOISE = perlin_table()
SEED_MODES = 4
DEPTH0 = q23(0.15)
DSPAN = q23(0.82)
GOLD = q23(0.6180339887)
OFFMAX = len(NOISE) - 1 - 63 * 4


def seed_params(j):
    """(depth, stride, offset) of Perlin seed j, as the DSP computes them."""
    def s24(v):
        v &= 0xFFFFFF
        return v - (1 << 24) if v & 0x800000 else v
    depth = DEPTH0 + ((2 * (j << 16) * DSPAN) >> 24)
    stride = 1 + (j >> 5)
    frac = ((2 * j * GOLD) & 0xFFFFFF) >> 1
    offset = (2 * frac * OFFMAX) >> 24
    return depth, stride, offset

PITCH_AT = 0
QTR_AT = PITCH_AT + len(PITCH)
DECAY_AT = QTR_AT + len(QTR)
SPEED_AT = DECAY_AT + len(DECAY)
EXPC_AT = SPEED_AT + len(SPEED)
LOGC_AT = EXPC_AT + len(EXPC)
# DEC 0 end fade: gain at the end of release block k = 1..8, 1 - smoothstep(k / 8)
FADE8 = [q23(1 - (3 * (k / 8) ** 2 - 2 * (k / 8) ** 3)) for k in range(9)]
FADE8_AT = LOGC_AT + len(LOGC)
NOISE_AT = FADE8_AT + len(FADE8)
TABLES = PITCH + QTR + DECAY + SPEED + EXPC + LOGC + FADE8 + [v & 0xFFFFFF for v in NOISE]
# Transient draft (SMP-TR): THRS 0..127 -> the largest onset q = reference / energy
# accepted, Q15: the energy must rise by 1.25 (THRS 0) .. 40 times (THRS 127).
QTHR = [round(32768 / (1.25 * 32 ** (t / 127))) for t in range(128)]
QTHR_AT = len(TABLES)
TABLES = TABLES + QTHR


def dc(values):
    return ["        dc      " + ",".join("$%06x" % v for v in values[i:i + 8]) for i in range(0, len(values), 8)]


if __name__ == "__main__":
    lines = ["; Generated by gen_tables.py: do not edit.",
             f"TB_PITCH equ {PITCH_AT}", f"TB_QTR  equ {QTR_AT}", f"TB_DECAY equ {DECAY_AT}",
             f"TB_SPEED equ {SPEED_AT}", f"TB_EXPC equ {EXPC_AT}", f"TB_LOGC equ {LOGC_AT}",
             f"TB_FADE8 equ {FADE8_AT}", f"TB_NOISE equ {NOISE_AT}",
             f"SEED_MODES equ {SEED_MODES}", f"NOISE_MAX equ {NOISE_MAX}", f"DEPTH0 equ ${DEPTH0:06x}",
             f"DSPAN equ ${DSPAN:06x}", f"GOLD equ ${GOLD:06x}", f"OFFMAX equ {OFFMAX}",
             "TABLES:", "; pitch 2^(n/12)/4, n = 0..12"] + dc(PITCH) \
        + ["; 1 - k/4, k = 0..4"] + dc(QTR) + ["; decay per block, DEC 0..127"] + dc(DECAY) \
        + [f"; playhead speed for TIME 0..127 (8192 = normal), curve {TIME_CURVE:.4f}"] + dc(SPEED) \
        + ["; EXP slice curve, 65 points"] + dc(EXPC) + ["; LOG slice curve, 65 points"] + dc(LOGC) \
        + ["; DEC 0 end fade, 1 - smoothstep(k/8), k = 0..8"] + dc(FADE8) \
        + [f"; Perlin noise, {len(NOISE)} entries, +-{NOISE_MAX}"] + dc([v & 0xFFFFFF for v in NOISE]) \
        + [f"TB_QTHR equ {QTHR_AT}", "; THRS 0..127: largest onset q (reference / energy), Q15"] + dc(QTHR)
    Path(__file__).with_name("tables.inc").write_text("\n".join(lines) + "\n")
    print("wrote tables.inc:", len(TABLES), "words")
    for j in (0, 31, 32, 63, 64, 95, 96, 123):
        d, s, o = seed_params(j)
        w = [NOISE_MAX + ((2 * NOISE[o + k * s] * d) >> 24) for k in range(8)]
        print(f"  seed {j + SEED_MODES:3d}: depth {d / Q23:.3f} stride {s} offset {o:3d}  8 slices %:",
              [round(100 * v / sum(w)) for v in w])
